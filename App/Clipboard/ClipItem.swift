import AppKit
import CryptoKit

/// One thing that was copied, with everything that was on the clipboard for it (so copying it
/// again brings back its formatting, its image, or whatever else the app put there). Files keep
/// only their paths, never the files themselves.
struct ClipItem: Codable, Identifiable, Equatable {
    enum Kind: String, Codable { case text, image, files, other }

    /// One kind of data on the clipboard and the file it's kept in (in the item's folder).
    struct Representation: Codable, Equatable {
        var type: String
        var file: String
    }

    var id = UUID()
    var kind: Kind
    /// The plain text (the paths, one per line, for files), cut short: for the list and search.
    var text: String
    /// The files that were copied.
    var paths: [String] = []
    /// What was on the clipboard, per pasteboard item (a copy of several things has several).
    var pasteboardItems: [[Representation]] = []
    var sourceBundleID: String?
    var sourceName: String?
    var firstCopied: Date
    var lastCopied: Date
    var copyCount = 1
    /// Pinned items stay at the top, in the order they were pinned, and are never cleared.
    var pinnedAt: Date?
    /// The same thing copied again moves this item to the top instead of adding another.
    var key: String
    var imageWidth: Int?
    var imageHeight: Int?
    var hasThumbnail = false

    var isPinned: Bool { pinnedAt != nil }
    var isText: Bool { kind == .text }

    /// One line for the list.
    var title: String {
        switch kind {
        case .text:
            let line = text.prefix(400).split(whereSeparator: \.isWhitespace).joined(separator: " ")
            return line.isEmpty ? "Blank Space" : line
        case .files:
            let names = paths.map { (($0 as NSString).lastPathComponent as String) }
            return names.count == 1 ? names[0] : "\(names[0]) and \(names.count - 1) more"
        case .image:
            if let imageWidth, let imageHeight { return "Image  \(imageWidth) × \(imageHeight)" }
            return "Image"
        case .other:
            return "Copied from \(sourceName ?? "an App")"
        }
    }

    /// The most text kept in the list's index (the full text is in the item's files).
    static let textLimit = 20_000
}

/// What was just copied, read off the clipboard (before it's stored).
struct Capture {
    var kind: ClipItem.Kind
    var text: String
    var paths: [String] = []
    var items: [[(type: String, data: Data)]] = []
    var key: String
    var imageSize: CGSize?
    var thumbnail: Data?
    var sourceBundleID: String?
    var sourceName: String?

    /// Marks that apps put on the clipboard for things that shouldn't be kept in a history:
    /// passwords and other secrets, and copies made for a moment (nspasteboard.org's markers,
    /// plus older ones from 1Password, TypeIt4Me, KeeWeb and Keyboard Maestro).
    static let skipMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.typeit4me.clipping",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]

    /// Kinds of data not worth keeping or putting back: Universal Clipboard's marker, and
    /// promises of data that only the app that copied it can fulfil.
    private static func isKept(_ type: String) -> Bool {
        !(type == "com.apple.is-remote-clipboard" || type.contains("promise") || type.contains("Promise"))
    }

    /// Past this, only the main kinds of data (text, formatting, images) are kept.
    private static let sizeLimit = 64 << 20
    private static let mainTypes: Set<String> = [
        NSPasteboard.PasteboardType.string.rawValue, NSPasteboard.PasteboardType.rtf.rawValue,
        NSPasteboard.PasteboardType.rtfd.rawValue, NSPasteboard.PasteboardType.html.rawValue,
        NSPasteboard.PasteboardType.png.rawValue, NSPasteboard.PasteboardType.tiff.rawValue,
        NSPasteboard.PasteboardType.URL.rawValue,
    ]

    /// Reads what's on the clipboard now, or nil if there's nothing to keep.
    static func read(from pasteboard: NSPasteboard, source: NSRunningApplication?) -> Capture? {
        guard let pbItems = pasteboard.pasteboardItems, !pbItems.isEmpty else { return nil }
        let allTypes = Set(pbItems.flatMap { $0.types.map(\.rawValue) })
        guard allTypes.isDisjoint(with: skipMarkers) else { return nil }
        let sourceID = source?.bundleIdentifier
        let sourceName = source?.localizedName

        // Files: only where they are.
        let urls = pbItems.compactMap { item -> URL? in
            guard let string = item.string(forType: .fileURL), let url = URL(string: string), url.isFileURL else { return nil }
            // Finder copies file reference URLs (file:///.file/id=…), which only mean something here.
            return ((url as NSURL).filePathURL ?? url).standardizedFileURL
        }
        if !urls.isEmpty && urls.count == pbItems.count {
            let paths = urls.map(\.path)
            let text = paths.joined(separator: "\n")
            return Capture(kind: .files, text: text, paths: paths, key: "files:" + text,
                           sourceBundleID: sourceID, sourceName: sourceName)
        }

        var items: [[(type: String, data: Data)]] = []
        var total = 0
        for pbItem in pbItems {
            var reps: [(type: String, data: Data)] = []
            for type in pbItem.types where isKept(type.rawValue) && !skipMarkers.contains(type.rawValue) {
                guard let data = pbItem.data(forType: type) else { continue }
                reps.append((type.rawValue, data))
                total += data.count
            }
            items.append(reps)
        }
        if total > sizeLimit {
            items = items.map { $0.filter { mainTypes.contains($0.type) } }
            total = items.reduce(0) { $0 + $1.reduce(0) { $0 + $1.data.count } }
            guard total <= sizeLimit else { return nil }
        }
        guard items.contains(where: { !$0.isEmpty }) else { return nil }

        let first = items.first ?? []
        let string = pasteboard.string(forType: .string)
            ?? first.first(where: { $0.type == NSPasteboard.PasteboardType.rtf.rawValue })
                .flatMap { NSAttributedString(rtf: $0.data, documentAttributes: nil)?.string }
            ?? ""
        let imageData = first.first(where: { $0.type == NSPasteboard.PasteboardType.png.rawValue })?.data
            ?? first.first(where: { $0.type == NSPasteboard.PasteboardType.tiff.rawValue })?.data

        // An image that comes with a name or a link (copying an image in a browser) is an image;
        // text that comes with a picture of itself (cells from a spreadsheet) is text.
        let looksLikeName = !string.contains(where: \.isWhitespace) && string.count < 2048
        if let imageData, string.isEmpty || looksLikeName {
            let source = CGImageSourceCreateWithData(imageData as CFData, nil)
            var size: CGSize?
            if let source, let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
               let width = properties[kCGImagePropertyPixelWidth] as? Int, let height = properties[kCGImagePropertyPixelHeight] as? Int {
                size = CGSize(width: width, height: height)
            }
            return Capture(kind: .image, text: string, items: items, key: "image:" + hash(imageData),
                           imageSize: size, thumbnail: source.flatMap(thumbnail),
                           sourceBundleID: sourceID, sourceName: sourceName)
        }
        if !string.isEmpty {
            return Capture(kind: .text, text: String(string.prefix(ClipItem.textLimit)), items: items,
                           key: "text:" + hash(Data(string.utf8)), sourceBundleID: sourceID, sourceName: sourceName)
        }
        var all = Data()
        for reps in items { for rep in reps { all.append(Data(rep.type.utf8)); all.append(rep.data) } }
        return Capture(kind: .other, text: "", items: items, key: "data:" + hash(all),
                       sourceBundleID: sourceID, sourceName: sourceName)
    }

    /// Plain text (an edit, a snippet, a path), as if it had been copied.
    static func text(_ string: String, sourceName: String? = nil) -> Capture {
        Capture(kind: .text, text: String(string.prefix(ClipItem.textLimit)),
                items: [[(NSPasteboard.PasteboardType.string.rawValue, Data(string.utf8))]],
                key: "text:" + hash(Data(string.utf8)), sourceBundleID: nil, sourceName: sourceName)
    }

    static func hash(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }

    /// A small PNG for the list (96 px on its longer side, for 2× screens).
    private static func thumbnail(_ source: CGImageSource) -> Data? {
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceThumbnailMaxPixelSize: 96,
            kCGImageSourceCreateThumbnailWithTransform: true,
        ]
        guard let image = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }
        return NSBitmapImageRep(cgImage: image).representation(using: .png, properties: [:])
    }
}
